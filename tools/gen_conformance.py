#!/usr/bin/env python3
"""Generate the C conformance test source from the official UAX29 test files.

Reads the official Unicode 18.0.0 conformance test data:
  data/ucd/18.0.0/ucd/auxiliary/GraphemeBreakTest.txt
  data/ucd/18.0.0/ucd/auxiliary/WordBreakTest.txt
  data/ucd/18.0.0/ucd/auxiliary/SentenceBreakTest.txt
  data/ucd/18.0.0/ucd/auxiliary/LineBreakTest.txt

and emits clike/tests/test_ucd18_conformance.c with segmenter vectors.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "clike" / "tests" / "test_ucd18_conformance.c"

TEST_FILES = [
    ("g", "GraphemeBreakTest.txt", "UNICODOID_BOUNDARY_GRAPHEME"),
    ("w", "WordBreakTest.txt", "UNICODOID_BOUNDARY_WORD"),
    ("s", "SentenceBreakTest.txt", "UNICODOID_BOUNDARY_SENTENCE"),
    ("l", "LineBreakTest.txt", "UNICODOID_BOUNDARY_LINE"),
]


def utf8_len(cp: int) -> int:
    if cp < 0x80:
        return 1
    if cp < 0x800:
        return 2
    if cp < 0x10000:
        return 3
    return 4


def parse_cases(path: Path):
    cases = []
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        body = s.split("#", 1)[0]
        tokens = body.split()
        cps = []
        breaks = []
        pending = True
        for t in tokens:
            if t == "\u00f7":
                pending = True
            elif t == "\u00d7":
                pending = False
            else:
                cps.append(int(t, 16))
                breaks.append(pending)
                pending = False
        ends = []
        off = 0
        for i, (cp, brk) in enumerate(zip(cps, breaks)):
            if brk and i > 0:
                ends.append(off)
            off += utf8_len(cp)
        ends.append(off)
        if not cps:
            ends = []
        cases.append((cps, ends))
    return cases


def fmt_bytes(cps) -> str:
    out = []
    for cp in cps:
        n = utf8_len(cp)
        if n == 1:
            out.append(f"0x{cp:02X}")
        elif n == 2:
            out.append(f"0x{0xC0 | (cp >> 6):02X},0x{0x80 | (cp & 0x3F):02X}")
        elif n == 3:
            out.append(f"0x{0xE0 | (cp >> 12):02X},0x{0x80 | ((cp >> 6) & 0x3F):02X},0x{0x80 | (cp & 0x3F):02X}")
        else:
            out.append(
                f"0x{0xF0 | (cp >> 18):02X},0x{0x80 | ((cp >> 12) & 0x3F):02X},0x{0x80 | ((cp >> 6) & 0x3F):02X},0x{0x80 | (cp & 0x3F):02X}"
            )
    return ", ".join(out)


HEADER = """#include "unicodoid/unicodoid.h"
#include "unicodoid/unicodoid_segmentation.h"
#include <stdio.h>
#include <string.h>

/* Generated by tools/gen_conformance.py from the official Unicode 18.0.0
   UAX29 conformance test files. Do not edit by hand. */

typedef struct {
    const uint8_t* bytes;
    size_t byte_len;
    const size_t* ends;
    size_t end_count;
} ucd18_case_t;

"""

FOOTER = """
static int uc_run_case(const ucd18_case_t* c, unicodoid_boundary_type_t bt) {
    const unicodoid_system_t* sys = unicodoid_system_get_utf8();
    unicodoid_segmenter_t seg;
    unicodoid_segment_t out;
    if (unicodoid_segmenter_init(&seg, sys, c->bytes, c->byte_len, bt) != UNICODOID_OK) {
        return -1;
    }
    size_t count = 0;
    size_t ends[256];
    while (count < 256 && unicodoid_segmenter_next(&seg, &out)) {
        ends[count++] = out.byte_offset + out.byte_length;
    }
    unicodoid_segmenter_free(&seg);
    int bad = 0;
    if ((size_t)count != c->end_count) {
        fprintf(stderr, "COUNT MISMATCH bt=%d got %zu want %zu\\n", (int)bt, count, c->end_count);
        bad = 1;
    }
    for (size_t i = 0; i < count && i < c->end_count; ++i) {
        if (ends[i] != c->ends[i]) {
            fprintf(stderr, "ENDS MISMATCH bt=%d case segment %zu got %zu want %zu\\n", (int)bt, i, ends[i], c->ends[i]);
            bad = 1;
        }
    }
    if (bad) {
        fprintf(stderr, "ACTUAL bt=%d count=%zu ends=", (int)bt, count);
        for (size_t i = 0; i < count; ++i) fprintf(stderr, "%zu,", ends[i]);
        fprintf(stderr, "\\n");
    }
    return bad;
}

static int uc_run_all(const ucd18_case_t* cases, size_t case_count, unicodoid_boundary_type_t bt) {
    int failures = 0;
    for (size_t i = 0; i < case_count; ++i) {
        int rc = uc_run_case(&cases[i], bt);
        if (rc != 0) {
            ++failures;
            fprintf(stderr, "FAIL conformance bt=%d case %zu rc=%d byte_len=%zu end_count=%zu ends=", (int)bt, i, rc, cases[i].byte_len, cases[i].end_count);
            for (size_t k = 0; k < cases[i].end_count; ++k) {
                fprintf(stderr, "%zu,", cases[i].ends[k]);
            }
            fprintf(stderr, " bytes=");
            for (size_t k = 0; k < cases[i].byte_len; ++k) {
                fprintf(stderr, "%02X", cases[i].bytes[k]);
            }
            fprintf(stderr, "\\n");
        }
    }
    return failures;
}

int main(void) {
    int failures = 0;
    failures += uc_run_all(g_cases, sizeof(g_cases) / sizeof(g_cases[0]), UNICODOID_BOUNDARY_GRAPHEME);
    failures += uc_run_all(w_cases, sizeof(w_cases) / sizeof(w_cases[0]), UNICODOID_BOUNDARY_WORD);
    failures += uc_run_all(s_cases, sizeof(s_cases) / sizeof(s_cases[0]), UNICODOID_BOUNDARY_SENTENCE);
    failures += uc_run_all(l_cases, sizeof(l_cases) / sizeof(l_cases[0]), UNICODOID_BOUNDARY_LINE);
    if (failures != 0) {
        fprintf(stderr, "conformance failures: %d\\n", failures);
        return 1;
    }
    printf("conformance ok\\n");
    return 0;
}
"""


def emit_type(short: str, cases, enum_line: str) -> str:
    parts = []
    for i, (cps, ends) in enumerate(cases):
        bs = f"uc_{short}_b_{i}"
        es = f"uc_{short}_e_{i}"
        parts.append(f"static const uint8_t {bs}[] = {{ {fmt_bytes(cps)} }};")
        parts.append(f"static const size_t {es}[] = {{ {', '.join(str(e) for e in ends)} }};")
    parts.append(f"static const ucd18_case_t {short}_cases[] = {{")
    for i, (cps, ends) in enumerate(cases):
        parts.append(
            "    { uc_" + short + "_b_" + str(i) + ", sizeof(uc_" + short + "_b_" + str(i) + "), "
            "uc_" + short + "_e_" + str(i) + ", sizeof(uc_" + short + "_e_" + str(i) + ") / sizeof(uc_" + short + "_e_" + str(i) + "[0]) },"
        )
    parts.append("};")
    parts.append(f"static const size_t {short}_case_count = {len(cases)};")
    return "\n".join(parts)


def main() -> None:
    out = [HEADER]
    for short, fname, enum_line in TEST_FILES:
        cases = parse_cases(ROOT / "data" / "ucd" / "18.0.0" / "ucd" / "auxiliary" / fname)
        out.append(f"/* {fname}: {len(cases)} cases */\n")
        out.append(emit_type(short, cases, enum_line))
        out.append("")
    out.append(FOOTER)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
